import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Whole-Tree Search for Caselore. Source: plugins/whole-tree-search/src
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	// Shared with the app: resolved at run time to the app's own instances (see the app's import map).
	external: [
		'@quire/api',
		'@codemirror/autocomplete',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lang-markdown',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/markdown',
		...builtinModules,
	],
	// Caselore loads plugins as ES modules.
	format: 'esm',
	platform: 'browser',
	target: 'es2022',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	// Not minified, so the released main.js can be read and reviewed.
	minify: false,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
